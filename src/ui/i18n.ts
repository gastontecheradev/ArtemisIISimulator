const TABLES: Readonly<Record<Locale, Readonly<Record<UiKey, string>>>> = { en: EN, es: ES };

// --- Language store ---
const listeners = new Set<() => void>();
const subscribe = (l: () => void): (() => void) => {
  listeners.add(l);
  return () => listeners.delete(l);
};

/** Sets the language of the interface and the simulation. */
export function setUiLocale(locale: Locale): void {
  if (locale === getLocale()) return;
  setLocale(locale);
  listeners.forEach((l) => l());
}

export const useLocale = (): Locale => useSyncExternalStore(subscribe, getLocale);

export type T = (key: UiKey, params?: Readonly<Record<string, string | number>>) => string;

export function translate(locale: Locale, key: UiKey, params?: Readonly<Record<string, string | number>>): string {
  const text = TABLES[locale][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

/** Hook: translation function for the current language. */
export function useT(): T {
  const locale = useLocale();
  return (key, params) => translate(locale, key, params);
}
